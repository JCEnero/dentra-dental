import 'dart:io';
import 'package:qr/qr.dart';

// Public sentinel only; never encode real Wi-Fi credentials in firmware tests.
void main(List<String> args) {
  const payload = 'DENTRA QR STACK SELF TEST';
  final qr = QrImage(
      QrCode.fromData(data: payload, errorCorrectLevel: QrErrorCorrectLevel.M));
  final bytes = List.filled((qr.moduleCount * qr.moduleCount + 7) ~/ 8, 0);
  for (var y = 0; y < qr.moduleCount; y++) {
    for (var x = 0; x < qr.moduleCount; x++) {
      final bit = y * qr.moduleCount + x;
      if (qr.isDark(y, x)) bytes[bit >> 3] |= 1 << (bit & 7);
    }
  }
  File(args.single).writeAsStringSync(
      '''// Generated by tool/generate_qr_self_test.dart. Public sentinel, no Wi-Fi data.
#pragma once
#include <cstring>
#include "quirc/quirc.h"

namespace dentra_qr {
inline bool decoderSelfTest(quirc_code* code, quirc_data* data) {
  static const uint8_t bitmap[] = {${bytes.join(',')}};
  static const char expected[] = "$payload";
  // Run on the actual loop-task stack; also exercise mirrored retries.
  for (int i = 0; i < 32; ++i) {
    std::memset(code, 0, sizeof(*code));
    code->size = ${qr.moduleCount};
    std::memcpy(code->cell_bitmap, bitmap, sizeof(bitmap));
    if (quirc_decode(code, data) != QUIRC_SUCCESS ||
        data->payload_len != sizeof(expected) - 1 ||
        std::memcmp(data->payload, expected, sizeof(expected) - 1)) return false;
    quirc_flip(code);
    auto error = quirc_decode(code, data);
    if (error != QUIRC_SUCCESS) { quirc_flip(code); error = quirc_decode(code, data); }
    if (error != QUIRC_SUCCESS || data->payload_len != sizeof(expected) - 1 ||
        std::memcmp(data->payload, expected, sizeof(expected) - 1)) return false;
  }
  return true;
}
}
''');
}
